"""Native Tk scenarios for framework capture, state and geometry regression."""
import tkinter as tk
from tkinter import ttk


class WidgetPage(ttk.Frame):
    def __init__(self, parent):
        super().__init__(parent, name="widgets")
        self.status = tk.StringVar(self, "尚未操作")
        ttk.Label(self, text="列表、层级树与 Canvas 图元", style="Heading.TLabel").pack(anchor="w")
        inputs = ttk.Frame(self, name="inputs")
        inputs.pack(fill="x", pady=8)
        ttk.Label(inputs, text="可编辑下拉 / 经典微调 / 只读 / 禁用").pack(anchor="w")
        self.combo = ttk.Combobox(inputs, name="combo", values=("红", "绿", "蓝"), width=14)
        self.combo.set("可编辑")
        self.spin = tk.Spinbox(inputs, name="spin", from_=0, to=100, width=8)
        self.readonly = ttk.Entry(inputs, name="readonly", width=16)
        self.readonly.insert(0, "只读文本")
        self.readonly.configure(state="readonly")
        self.disabled = ttk.Entry(inputs, name="disabled", width=16)
        self.disabled.insert(0, "禁用文本")
        self.disabled.configure(state="disabled")
        for widget in (self.combo, self.spin, self.readonly, self.disabled):
            widget.pack(side="left", padx=4)
        row = ttk.Frame(self, name="items")
        row.pack(fill="x", pady=10)
        self.listbox = tk.Listbox(row, name="list", height=6, exportselection=False)
        for value in ["重复项", "第二项", "重复项"] + ["项目 {}".format(i) for i in range(4, 21)]:
            self.listbox.insert("end", value)
        self.listbox.pack(side="left", padx=5)
        self.tree = ttk.Treeview(row, name="tree", columns=("value",), height=6)
        self.tree.heading("#0", text="层级")
        self.tree.heading("value", text="值")
        self.tree.column("#0", width=140)
        self.tree.column("value", width=90)
        self.tree.insert("", "end", iid="parent", text="父节点", values=("P",), open=True)
        self.tree.insert("parent", "end", iid="child", text="子节点", values=("C",))
        self.tree.insert("child", "end", iid="grandchild", text="孙节点", values=("G",))
        self.tree.pack(side="left", padx=8)
        self.canvas = tk.Canvas(row, name="canvas", width=300, height=180, background="white", scrollregion=(0, 0, 650, 220))
        self.canvas.create_rectangle(15, 15, 210, 120, fill="lightblue", tags=("background",))
        self.canvas.create_text(110, 65, text="Canvas 文字", tags=("caption",))
        self.canvas.create_oval(225, 20, 280, 75, fill="orange", tags=("circle",))
        self.canvas.create_text(450, 65, text="滚动后文字", tags=("scrolled",))
        self.canvas.create_text(100, 150, text="隐藏图元", tags=("hidden",), state="hidden")
        for tag in ("caption", "circle", "scrolled"):
            self.canvas.tag_bind(tag, "<Button-1>", lambda event, key=tag: self.status.set("Canvas: " + key))
        self.canvas.pack(side="left")
        controls = ttk.Frame(self, name="controls")
        controls.pack(fill="x")
        ttk.Button(controls, name="scroll", text="滚动 Canvas", command=lambda: self.canvas.xview_moveto(.5)).pack(side="left")
        ttk.Button(controls, name="reset", text="恢复 Canvas", command=lambda: self.canvas.xview_moveto(0)).pack(side="left")
        self.scale = tk.Scale(controls, name="scale", from_=0, to=100, orient="horizontal")
        self.scale.set(30)
        self.scale.pack(side="left", padx=12)
        self.progress = ttk.Progressbar(controls, name="progress", maximum=100, value=60)
        self.progress.pack(side="left")
        self.tabs = ttk.Notebook(self, name="states")
        for name, title, state in (("first", "可见页", "normal"), ("second", "第二页", "normal"), ("disabled", "禁用页", "disabled"), ("hidden", "隐藏页", "hidden")):
            pane = ttk.Frame(self.tabs, name=name, height=70)
            ttk.Label(pane, text=title + "内容").pack()
            self.tabs.add(pane, text=title, state=state)
        self.tabs.pack(fill="x", pady=12)
        ttk.Label(self, name="result", textvariable=self.status).pack(anchor="w")


class MenuTextPage(ttk.Frame):
    def __init__(self, parent):
        super().__init__(parent, name="semantics")
        self.status = tk.StringVar(self, "尚未操作")
        ttk.Label(self, text="独立菜单与 Text 标签", style="Heading.TLabel").pack(anchor="w")
        row = ttk.Frame(self, name="menus")
        row.pack(fill="x", pady=12)
        self.context = tk.Button(row, name="context", text="在这里右键")
        self.context.pack(side="left")
        self.context_menu = tk.Menu(self, name="context_menu", tearoff=False)
        self.context_menu.add_command(label="右键命令", command=lambda: self.status.set("已执行右键命令"))
        child = tk.Menu(self.context_menu, name="nested", tearoff=False)
        child.add_command(label="二级命令", command=lambda: self.status.set("已执行二级命令"))
        self.context_menu.add_cascade(label="更多操作", menu=child)
        self.context.bind("<Button-3>", lambda event: self.context_menu.tk_popup(event.x_root, event.y_root))
        for cls, name, label in ((tk.Menubutton, "classic", "经典菜单"), (ttk.Menubutton, "themed", "主题菜单")):
            button = cls(row, name=name, text=label)
            menu = tk.Menu(button, name="menu", tearoff=False)
            menu.add_command(label=label + "命令", command=lambda value=label: self.status.set("已执行" + value))
            menu.add_command(label="禁用命令", state="disabled")
            button.configure(menu=menu)
            button.pack(side="left", padx=12)
        self.option = tk.StringVar(self, "选项 A")
        tk.OptionMenu(row, self.option, "选项 A", "选项 B", "选项 C",
                      command=lambda value: self.status.set("已选择" + value)).pack(side="left")
        ttk.Label(self, text="点击蓝色文字验证回调；Ctrl+End / Ctrl+Home 验证滚动。链接仅更新下方结果，不打开网站。").pack(anchor="w")
        self.text = tk.Text(self, name="text", height=10, wrap="word")
        self.text.pack(fill="both", expand=True, pady=8)
        self.text.insert("end", "第一个链接\n普通标签文字\n第二个链接\n" + "可以换行的链接文字 " * 20 + "\n隐藏文字\n非连续标签 🚀\n" + "滚动测试行\n" * 30)
        for tag, line in (("first_link", 1), ("second_link", 3), ("wrapped_link", 4)):
            self.text.tag_add(tag, "{}.0".format(line), "{}.end".format(line))
            self.text.tag_configure(tag, foreground="blue", underline=True)
            self.text.tag_bind(tag, "<Button-1>", lambda event, key=tag: self.status.set("已点击 " + key))
        self.text.tag_add("style", "2.0", "2.end")
        self.text.tag_configure("style", foreground="darkgreen")
        self.text.tag_add("hidden", "5.0", "5.end")
        self.text.tag_configure("hidden", elide=True)
        self.text.tag_add("repeated", "6.0", "6.2", "6.6", "6.end")
        self.text.tag_add("overlay", "1.0", "1.end")
        self.text.tag_configure("overlay", background="#eef4ff")
        ttk.Label(self, name="result", textvariable=self.status).pack(anchor="w")
